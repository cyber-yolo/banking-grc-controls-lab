#!/usr/bin/env python3
"""Build the traceability matrix and the compliance dashboard.

Outputs (Markdown, committed after review):
  docs/traceability-matrix.md      requirement -> control -> evidence -> tests (from repository files only)
  reports/compliance-dashboard.md  control status per domain and per jurisdiction (from a results file)
  reports/control-status.csv       same data, flat, for a spreadsheet or Power BI

Usage:
  python tools/build_report.py                                  # matrix + dashboard of repository-only checks
  python tools/build_report.py --results reports/results.json   # dashboard of a lab run
  python tools/build_report.py --check                          # CI: fail if the committed matrix is stale
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import io
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import evaluate_controls as ev  # noqa: E402

STATUS_ORDER = ["EFFECTIVE", "DESIGN_ONLY", "PARTIAL", "NOT_EFFECTIVE", "NOT_ASSESSED", "MANUAL"]
STATUS_HELP = {
    "EFFECTIVE": "design and operating effectiveness assertions all PASS",
    "DESIGN_ONLY": "design assertions PASS, operating effectiveness not machine-tested yet",
    "PARTIAL": "some assertions PASS, others without evidence",
    "NOT_EFFECTIVE": "at least one assertion FAILS",
    "NOT_ASSESSED": "no evidence collected",
    "MANUAL": "no machine-checked assertion; reviewer sign-off in the run sheet",
}


def load_requirements(root: Path):
    reqs = {}
    for f in sorted((root / "requirements").glob("*.yaml")):
        doc = yaml.safe_load(f.read_text(encoding="utf-8"))
        for r in doc["requirements"]:
            r["_file"] = f.name
            r["_jurisdiction"] = doc["jurisdiction"]
            r["_verified"] = doc.get("verified_on")
            reqs[r["id"]] = r
    return reqs


def traceability(root: Path) -> str:
    reqs, controls = load_requirements(root), ev.load_controls(root)
    by_req = defaultdict(list)
    for c in controls:
        for rid in c["requirements"]:
            by_req[rid].append(c)
    out = io.StringIO()
    w = out.write
    w("# Traceability matrix\n\n")
    w("Generated by `tools/build_report.py` from `requirements/` and `controls/sheets/`. Do not edit by hand.\n\n")
    w("References are paraphrased and **TO VERIFY** until the file's `verified_on` is set (see `requirements/README.md`).\n\n")
    w("## Requirement to control\n\n")
    w("| Jurisdiction | Requirement | Reference | Confidence | Scope | Controls | Tests |\n|---|---|---|---|---|---|---|\n")
    for rid, r in reqs.items():
        ctl = by_req.get(rid, [])
        tests = [c["tests"][k]["id"] for c in ctl for k in ("design", "effectiveness")]
        scope = r["lab_scope"] if ctl or r["lab_scope"] == "out" else r["lab_scope"] + " (unmapped)"
        conf = r["confidence"] + ("" if r["_verified"] else ", TO VERIFY")
        w(f"| {r['_jurisdiction']} | {rid} | {r['reference']} | {conf} | {scope} | "
          f"{', '.join(c['id'] for c in ctl) or '-'} | {', '.join(tests) or '-'} |\n")
    w("\n## Control to evidence\n\n")
    w("| Control | Name | Automation | Evidence | Assertions | Detections |\n|---|---|---|---|---|---|\n")
    for c in controls:
        w(f"| {c['id']} | {c['name']} | {c['automation']} | {', '.join(e['id'] + ' ' + e['item'] for e in c['evidence'])} | "
          f"{len(c.get('assertions') or [])} | {', '.join(c.get('detections') or []) or '-'} |\n")
    w("\n## Out of scope requirements\n\n")
    for rid, r in reqs.items():
        if r["lab_scope"] == "out":
            w(f"- **{rid}** ({r['reference']}): {r.get('note', '')}\n")
    return out.getvalue()


def dashboard(root: Path, res: dict) -> tuple[str, str]:
    reqs = load_requirements(root)
    sheets = {c["id"]: c for c in ev.load_controls(root)}
    counts = Counter(c["status"] for c in res["controls"])
    out = io.StringIO()
    w = out.write
    w("# Compliance dashboard\n\n")
    w(f"Evaluated {res['evaluated_at']} (as of {res['as_of']}). Evidence run: `{res['run_id'] or 'none (repository-only checks)'}`. "
      f"Repository commit: `{(res['repo_commit'] or 'n/a')[:12]}`.\n\n")
    w("Generated by `tools/build_report.py`. A status is only as good as the evidence behind it: open the run manifest before quoting it.\n\n")
    w("## Summary\n\n| Status | Controls | Meaning |\n|---|---|---|\n")
    for s in STATUS_ORDER:
        w(f"| {s} | {counts.get(s, 0)} | {STATUS_HELP[s]} |\n")
    w("\n## By jurisdiction\n\nA control counts for a jurisdiction when it maps at least one requirement of that jurisdiction.\n\n")
    w("| Jurisdiction | " + " | ".join(STATUS_ORDER) + " |\n|---|" + "---|" * len(STATUS_ORDER) + "\n")
    for j in ("EU", "LU", "CH"):
        cnt = Counter(c["status"] for c in res["controls"]
                      if any(reqs.get(r, {}).get("_jurisdiction") == j for r in sheets[c["id"]]["requirements"]))
        w(f"| {j} | " + " | ".join(str(cnt.get(s, 0)) for s in STATUS_ORDER) + " |\n")
    w("\n## Controls\n\n| Control | Domain | Status | Assertions (PASS / total) | Detail of first non-PASS |\n|---|---|---|---|---|\n")
    rows = []
    for c in res["controls"]:
        a = c["assertions"]
        npass = sum(1 for x in a if x["status"] == ev.PASS)
        first = next((f"{x['id']} {x['status']}: {x['detail']}" for x in a if x["status"] != ev.PASS), "")
        w(f"| {c['id']} {c['name']} | {c['domain']} | **{c['status']}** | {npass} / {len(a)} | {first.replace('|', '/')} |\n")
        rows.append([c["id"], c["name"], c["domain"], c["status"], npass, len(a), res["as_of"], res["run_id"] or ""])
    csv_out = io.StringIO()
    cw = csv.writer(csv_out, lineterminator="\n")
    cw.writerow(["control", "name", "domain", "status", "assertions_pass", "assertions_total", "as_of", "run_id"])
    cw.writerows(rows)
    return out.getvalue(), csv_out.getvalue()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--results", type=Path, help="results JSON from evaluate_controls.py")
    ap.add_argument("--check", action="store_true", help="only check that docs/traceability-matrix.md is up to date")
    args = ap.parse_args()
    root = args.root.resolve()
    matrix = traceability(root)
    target = root / "docs" / "traceability-matrix.md"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != matrix:
            print("docs/traceability-matrix.md is stale: run python tools/build_report.py")
            return 1
        print("traceability matrix up to date")
        return 0
    target.write_text(matrix, encoding="utf-8")
    if args.results:
        res = json.loads(args.results.read_text(encoding="utf-8"))
    else:
        res = ev.evaluate(root, None, dt.date.today())
    md, flat = dashboard(root, res)
    (root / "reports").mkdir(exist_ok=True)
    (root / "reports" / "compliance-dashboard.md").write_text(md, encoding="utf-8")
    (root / "reports" / "control-status.csv").write_text(flat, encoding="utf-8")
    print("wrote docs/traceability-matrix.md, reports/compliance-dashboard.md, reports/control-status.csv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
